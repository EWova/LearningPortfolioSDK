    #region Scheme JSON 模型（對應後端 GET /api/projects/{projectId}/scheme）

    [Serializable]
    public class ProjectSchemeJson
    {
        public int SchemeVersion;
        public string ProjectId;
        public string AppId;
        public string Name;
        public string Hash;
        public List<ProjectSchemePageJson> Pages = new();
        public List<ProjectSchemeProgressNodeJson> ProgressNodes = new();
    }

    [Serializable]
    public class ProjectSchemePageJson
    {
        public int Index;
        public string Key;
        public string Label;
        public bool IsOverview;
        public List<ProjectSchemeColumnJson> Columns = new();
    }

    [Serializable]
    public class ProjectSchemeColumnJson
    {
        public string Key;
        public string Label;
        public int SortOrder;
        public bool IsReadOnly;
        public string FieldType;
    }

    [Serializable]
    public class ProjectSchemeProgressNodeJson
    {
        public string Id;
        public string Label;
        public string Path;
        public List<string> AncestorLabels = new();
        public int Depth;
        public bool IsLeaf;
        public bool Hidden;
    }

